export interface ProductDef {
  sku: string;
  name: string;
  category: string;
  uom: string;
  price: number;
  cost: number;
  type?: "storable" | "service" | "consumable";
  /** Harga ekspor (USD) untuk produk yang dijual ke luar negeri. */
  usd?: number;
  /** Stok awal 1 Jan 2026. */
  stock?: number;
  costMethod?: "fifo" | "average";
}

